def code_type(rang: int) -> str:
    return f"T{rang:02d}"


def code_motif(rang_type: int, rang_motif: int) -> str:
    return f"T{rang_type:02d}_M{rang_motif:02d}"


def description_type(famille: str, note: str | None) -> str:
    return FAMILLES[famille] + (f" · {note}" if note else "")
